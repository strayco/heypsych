#!/usr/bin/env node
/**
 * Fix SEO issues in treatment JSON files
 *
 * This script:
 * 1. Removes obsolete schema_injection fields
 * 2. Fixes canonical URLs (singular → plural, adds www)
 * 3. Removes redundant seo.title and seo.description (let code auto-generate)
 *
 * Usage:
 *   node scripts/fix-treatment-json-seo.js
 *   node scripts/fix-treatment-json-seo.js --dry-run  # Preview changes only
 */

const fs = require('fs');
const path = require('path');

const DRY_RUN = process.argv.includes('--dry-run');
const TREATMENTS_DIR = path.join(__dirname, '../data/treatments');

let filesProcessed = 0;
let filesModified = 0;
let issues = [];

/**
 * Fix a single JSON file
 */
function fixTreatmentFile(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8');
    const data = JSON.parse(content);

    let modified = false;
    const fileIssues = [];

    // 1. Remove schema_injection (obsolete - code auto-generates schema)
    if (data.schema_injection) {
      fileIssues.push('Removed schema_injection');
      delete data.schema_injection;
      modified = true;
    }

    // 2. Fix canonical URL if present
    if (data.seo?.canonical) {
      const oldCanonical = data.seo.canonical;
      let newCanonical = oldCanonical;

      // Fix singular /treatment/ → plural /treatments/
      if (newCanonical.includes('/treatment/')) {
        newCanonical = newCanonical.replace('/treatment/', '/treatments/');
        fileIssues.push(`Fixed path: /treatment/ → /treatments/`);
        modified = true;
      }

      // Add www subdomain
      if (newCanonical.startsWith('https://heypsych.com')) {
        newCanonical = newCanonical.replace('https://heypsych.com', 'https://www.heypsych.com');
        fileIssues.push('Added www subdomain');
        modified = true;
      }

      if (newCanonical !== oldCanonical) {
        data.seo.canonical = newCanonical;
      }
    }

    // 3. Remove seo.title and seo.description (let MetadataFactory auto-generate)
    // Only remove if they follow the standard pattern - keep custom ones
    if (data.seo?.title) {
      // If title looks auto-generated, remove it
      const isAutoGenerated =
        data.seo.title.includes('Uses, Side Effects, Dosage') ||
        data.seo.title.includes('Dosing, Black Box Warnings');

      if (isAutoGenerated) {
        fileIssues.push('Removed auto-generated seo.title (will be generated by code)');
        delete data.seo.title;
        modified = true;
      }
    }

    if (data.seo?.description) {
      // If description mentions standard terms, it's likely auto-generated
      const isAutoGenerated =
        data.seo.description.includes('comprehensive guide') ||
        data.seo.description.includes('is used to treat');

      if (isAutoGenerated) {
        fileIssues.push('Removed auto-generated seo.description (will be generated by code)');
        delete data.seo.description;
        modified = true;
      }
    }

    // 4. Ensure seo.no_index is set (default false)
    if (data.seo && data.seo.no_index === undefined) {
      data.seo.no_index = false;
      fileIssues.push('Added seo.no_index = false');
      modified = true;
    }

    // Write changes
    if (modified) {
      filesModified++;

      if (!DRY_RUN) {
        const newContent = JSON.stringify(data, null, 2) + '\n';
        fs.writeFileSync(filePath, newContent, 'utf-8');
      }

      issues.push({
        file: path.relative(process.cwd(), filePath),
        issues: fileIssues
      });
    }

    filesProcessed++;

  } catch (error) {
    console.error(`Error processing ${filePath}:`, error.message);
  }
}

/**
 * Recursively process all JSON files in treatments directory
 */
function processDirectory(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      processDirectory(fullPath);
    } else if (entry.isFile() && entry.name.endsWith('.json')) {
      fixTreatmentFile(fullPath);
    }
  }
}

// Main execution
console.log('🔧 Fixing SEO issues in treatment JSON files...\n');
console.log(`Mode: ${DRY_RUN ? 'DRY RUN (no files will be modified)' : 'LIVE (files will be updated)'}\n`);

processDirectory(TREATMENTS_DIR);

// Report results
console.log('\n📊 Summary:');
console.log(`   Files processed: ${filesProcessed}`);
console.log(`   Files modified: ${filesModified}`);

if (issues.length > 0) {
  console.log('\n📝 Changes made:');
  issues.forEach(({ file, issues: fileIssues }) => {
    console.log(`\n   ${file}:`);
    fileIssues.forEach(issue => {
      console.log(`      ✓ ${issue}`);
    });
  });
}

if (DRY_RUN) {
  console.log('\n⚠️  This was a dry run. No files were modified.');
  console.log('   Run without --dry-run to apply changes.');
} else {
  console.log('\n✅ All fixes applied successfully!');
}

console.log('\n📋 Next steps:');
console.log('   1. Review the changes with: git diff data/treatments/');
console.log('   2. Test a few pages locally to confirm metadata generation');
console.log('   3. Commit the changes');
